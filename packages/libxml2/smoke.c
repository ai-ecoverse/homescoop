static int parse_expect(const char *name, const unsigned char *doc, unsigned len,
                        const char *expect) {
  xmlDocPtr d = xmlReadMemory((const char *)doc, (int)len, name, name, 0);
  if (!d) {
    fprintf(stderr, "FAIL %s: xmlReadMemory\n", name);
    return 1;
  }
  xmlNodePtr root = xmlDocGetRootElement(d);
  xmlChar *text = root ? xmlNodeGetContent(root) : NULL;
  int rc = 0;
  if (!text || strcmp((char *)text, expect) != 0) {
    fprintf(stderr, "FAIL %s: got [%s] want [%s]\n", name,
            text ? (char *)text : "(null)", expect);
    rc = 1;
  } else {
    fprintf(stderr, "ok %s\n", name);
  }
  xmlFree(text);
  xmlFreeDoc(d);
  return rc;
}

int main(void) {
  xmlInitParser();
  const char cafe[] = "caf\xc3\xa9";
  const char jp[] = "\xe6\x97\xa5\xe6\x9c\xac\xe8\xaa\x9e";
  int fails = 0;
  fails += parse_expect("UTF-8", DOC_UTF_8, sizeof(DOC_UTF_8), "Hello");
  fails += parse_expect("ISO-8859-1", DOC_ISO_8859_1, sizeof(DOC_ISO_8859_1), cafe);
  fails += parse_expect("WINDOWS-1252", DOC_WINDOWS_1252, sizeof(DOC_WINDOWS_1252),
                        cafe);
  fails += parse_expect("SHIFT_JIS", DOC_SHIFT_JIS, sizeof(DOC_SHIFT_JIS), jp);
  fails += parse_expect("EUC-JP", DOC_EUC_JP, sizeof(DOC_EUC_JP), jp);
  fails += parse_expect("UTF-16", DOC_UTF_16, sizeof(DOC_UTF_16), "Hello");
  fails += parse_expect("UTF-32", DOC_UTF_32, sizeof(DOC_UTF_32), "Hello");
  xmlCleanupParser();
  if (fails) {
    fprintf(stderr, "libxml2 iconv smoke: %d failed\n", fails);
    return 1;
  }
  fprintf(stderr, "libxml2 iconv smoke: all encodings ok\n");
  return 0;
}

function lockHunks (name, text) {
  return [...text.matchAll(/^diff --git a\/Cargo\.lock b\/Cargo\.lock$/gm)].map(() => `${name} edits Cargo.lock; lock.json (apply.sh's lock.mjs) edits it by crate name`);
}

function checkNoLockHunks (patches) {
  const found = patches.flatMap(([name, text]) => lockHunks(name, text));
  assert.deepEqual(found, [], found.join('; '));
}

test('no packages/wasi-uv series patch carries a Cargo.lock hunk', () => {
  assert.ok(series.length >= 6);
  checkNoLockHunks(series.map((f) => [f, read(f)]));
});


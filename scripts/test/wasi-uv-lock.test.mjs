const EDITS = {
  unlock: [['hyper-util', '0.1.21']],
  dependencies: { 'hyper-util': ['wasix-net'], uv: ['libc', 'itertools 0.10.5'], 'uv-shell': ['wasix-command'] },
  packages: [
    { name: 'wasix-command', version: '0.1.0', dependencies: ['tokio', 'libc'] },
    { name: 'wasix-net', version: '0.1.0', source: 'registry+https://github.com/rust-lang/crates.io-index', checksum: 'ffff' },
  ],
};

test('editLock unlocks, adds sorted dependencies and inserts packages by name', () => {
  const r = editLock(LOCK, EDITS);
  assert.deepEqual([r.unlocked, r.added, r.packages], [1, 4, 2]);
  assert.match(r.text, /\[\[package\]\]\nname = "hyper-util"\nversion = "0\.1\.21"\ndependencies = \[\n "bytes",\n "tokio",\n "wasix-net",\n "windows-registry",\n\]\n\n\[\[package\]\]\nname = "itertools"/);
  assert.match(r.text, /name = "uv"\nversion = "0\.13\.8"\ndependencies = \[\n "itertools 0\.10\.5",\n "itertools 0\.14\.0",\n "libc",\n "owo-colors",\n\]\n/);
  assert.match(r.text, /name = "uv-shell"\nversion = "0\.0\.100"\ndependencies = \[\n "uv-static",\n "wasix-command",\n "which",\n\]\n\n\[\[package\]\]\nname = "wasix-command"\nversion = "0\.1\.0"\ndependencies = \[\n "libc",\n "tokio",\n\]\n\n\[\[package\]\]\nname = "wasix-net"\nversion = "0\.1\.0"\nsource = "registry\+https:\/\/github\.com\/rust-lang\/crates\.io-index"\nchecksum = "ffff"\n\n\[\[package\]\]\nname = "zstd"/);
  assert.ok(r.text.endsWith('checksum = "eeee"\n'));
  assert.ok(r.text.startsWith('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "hyper-util"'));
  assert.equal(r.text.split('\n\n\n').length, 1);
});

test('editLock with no edits keeps the lock byte for byte', () => {
  assert.equal(editLock(LOCK, {}).text, LOCK);
});

test('NEGATIVE: editLock refuses a lock it cannot edit unambiguously', () => {
  assert.throws(() => editLock(LOCK, { unlock: [['hyper-util', '0.1.20']] }), /has 0 hyper-util 0\.1\.20 entries/);
  assert.throws(() => editLock(LOCK, { dependencies: { uv: ['itertools'] } }), /has 2 itertools entries, want 1 \(name a version/);
  assert.throws(() => editLock(LOCK, { dependencies: { uv: ['owo-colors'] } }), /has 0 owo-colors entries/);
  assert.throws(() => editLock(LOCK, { dependencies: { uv: ['itertools 0.14.0'] } }), /uv already depends on itertools 0\.14\.0/);
  assert.throws(() => editLock(LOCK, { dependencies: { 'uv-auth': ['libc'] } }), /has 0 uv-auth entries/);
  assert.throws(() => editLock(LOCK, { packages: [{ name: 'libc', version: '0.2.190' }] }), /already has libc/);
  assert.throws(() => editLock(editLock(LOCK, { unlock: [['hyper-util', '0.1.21']] }).text, { unlock: [['hyper-util', '0.1.21']] }), /no registry source and checksum to drop/);
});

test("lockEdits unlocks exactly the crates/*.patch crates, with lock.json's additions", () => {
  const crates = readdirSync(new URL('crates/', dir)).filter((f) => f.endsWith('.patch')).map((f) => f.replace(/\.patch$/, '')).sort();
  const e = lockEdits();
  assert.deepEqual(e.unlock.map(([n, v]) => `${n}-${v}`), crates);
  assert.deepEqual(e.dependencies, spec.dependencies);
  assert.deepEqual(e.packages, spec.packages);
});

function manifestDeps (patches) {
  const out = {};
  for (const text of patches) {
    for (const [, path, body] of text.matchAll(/^diff --git a\/crates\/([^/]+)\/Cargo\.toml b\/[^\n]*\n([\s\S]*?)(?=^diff --git |(?![\s\S]))/gm)) {
      const added = [...body.matchAll(/^\+([a-z0-9_-]+) = /gm)].map((m) => m[1]);
      const removed = new Set([...body.matchAll(/^-([a-z0-9_-]+) = /gm)].map((m) => m[1]));
      const net = added.filter((d) => !removed.has(d));
      if (net.length) out[path] = [...(out[path] ?? []), ...net].sort();
    }
  }
  return out;
}

function checkSpecMatchesSeries (lockSpec, patches, hyperUtilPatch, wasixCommandToml) {
  const fromSeries = manifestDeps(patches);
  const declared = Object.fromEntries(Object.entries(lockSpec.dependencies).filter(([k]) => k === 'uv' || k.startsWith('uv-')).map(([k, v]) => [k, [...v].sort()]));
  assert.deepEqual(declared, fromSeries, "lock.json's uv crates gain exactly the dependencies the series adds to their Cargo.toml");
  assert.match(hyperUtilPatch, /^\+\[target\.'cfg\(target_os = "wasi"\)'\.dependencies\.wasix-net\]$/m);
  assert.deepEqual(lockSpec.dependencies['hyper-util'], ['wasix-net']);
  assert.deepEqual(lockSpec.dependencies.indicatif, ['web-time']);
  const wc = lockSpec.packages.find((p) => p.name === 'wasix-command');
  assert.equal(wc.version, /^version = "([^"]+)"$/m.exec(wasixCommandToml)[1], 'lock.json wasix-command is crates/wasix-command/Cargo.toml version');
  assert.deepEqual([...wc.dependencies].sort(), ['libc', 'tokio']);
  assert.equal(wc.source, undefined);
  const wn = lockSpec.packages.find((p) => p.name === 'wasix-net');
  assert.equal(wn.source, 'registry+https://github.com/rust-lang/crates.io-index');
  assert.match(wn.checksum, /^[0-9a-f]{64}$/);
}

const wasixCommandToml = readFileSync(new URL('../../crates/wasix-command/Cargo.toml', import.meta.url), 'utf8');
const hyperUtil = read(readdirSync(new URL('crates/', dir)).filter((f) => f.startsWith('hyper-util-')).map((f) => `crates/${f}`)[0]);

test("lock.json matches the series' manifests, hyper-util's wasix-net and crates/wasix-command", () => {
  checkSpecMatchesSeries(spec, series.map(read), hyperUtil, wasixCommandToml);
  assert.equal(spec.dependencies.uv.includes('wasix-command'), false, 'crates/uv has no wasix-command dependency');
});

test('NEGATIVE: a lock.json that adds wasix-command to the uv package, or misses a crate, fails', () => {
  const withUv = structuredClone(spec);
  withUv.dependencies.uv = [...withUv.dependencies.uv, 'wasix-command'];
  assert.throws(() => checkSpecMatchesSeries(withUv, series.map(read), hyperUtil, wasixCommandToml), /exactly the dependencies the series adds/);
  const missing = structuredClone(spec);
  delete missing.dependencies['uv-shell'];
  assert.throws(() => checkSpecMatchesSeries(missing, series.map(read), hyperUtil, wasixCommandToml), /exactly the dependencies the series adds/);
  assert.throws(() => checkSpecMatchesSeries(spec, series.map(read), hyperUtil, wasixCommandToml.replace('version = "0.1.0"', 'version = "0.2.0"')), /crates\/wasix-command\/Cargo\.toml version/);
});

#!/usr/bin/env node
/**
 * Generate the root README package table from packages/<name>/package/package.json
 * (name, description) and recipe.yaml `builder:` (retired packages go in their
 * own table). No version column: npm shows the current one, and a version per
 * row would make every bump edit README.md, so concurrent bumps of neighbouring
 * rows conflict. Descriptions can carry upstream versions, which
 * sync-package-version rewrites on an upstream bump, so ladder-pr's recipe-sha
 * job regenerates the table too. Private packages are left out. The table lives between the
 * `<!-- packages:start -->` and `<!-- packages:end -->` markers (#639, #647, #659).
 *
 *   node scripts/readme-table.mjs            # print the table
 *   node scripts/readme-table.mjs --write    # rewrite README.md in place
 *   node scripts/readme-table.mjs --check    # exit 1 if README.md differs
 *
 * scripts/test/readme-table.test.mjs runs --check in ladder-pr.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const START = '<!-- packages:start (generated by scripts/readme-table.mjs --write; do not edit) -->';
export const END = '<!-- packages:end -->';

const defaultRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

const cell = (s) => String(s ?? '').replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim();

/** @param {string} root */
export function listPackages(root = defaultRoot) {
  const dir = join(root, 'packages');
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const pkgPath = join(dir, name, 'package', 'package.json');
    if (!existsSync(pkgPath)) continue;
    const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
    if (pkg.private) continue;
    const recipePath = join(dir, name, 'recipe.yaml');
    const recipe = existsSync(recipePath) ? readFileSync(recipePath, 'utf8') : '';
    const m = recipe.match(/^builder:\s*["']?([\w-]+)/m);
    out.push({
      dir: name,
      name: pkg.name,
      version: pkg.version,
      description: pkg.description || '',
      retired: m?.[1] === 'retired',
    });
  }
  return out;
}

/** @param {string} root */
export function renderTable(root = defaultRoot) {
  const pkgs = listPackages(root);
  const rows = (list) =>
    list.map(
      (p) =>
        `| [\`${cell(p.name)}\`](https://www.npmjs.com/package/${p.name}) | [recipe](packages/${p.dir}) | ${cell(p.description)} |`
    );
  const head = ['| npm | recipe | description |', '| --- | --- | --- |'];
  const active = pkgs.filter((p) => !p.retired);
  const retired = pkgs.filter((p) => p.retired);
  const lines = [START, ...head, ...rows(active)];
  if (retired.length) {
    lines.push('', 'Retired (`builder: retired`; no longer built or published):', '', ...head, ...rows(retired));
  }
  lines.push(END);
  return lines.join('\n');
}

/**
 * @param {string} readme
 * @param {string} table
 */
export function replaceTable(readme, table) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`README.md: missing ${START} … ${END} markers`);
  return readme.slice(0, a) + table + readme.slice(b + END.length);
}

/** @param {string} root */
export function checkReadme(root = defaultRoot) {
  const path = join(root, 'README.md');
  const readme = readFileSync(path, 'utf8');
  const want = replaceTable(readme, renderTable(root));
  return { path, readme, want, ok: want === readme };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const arg = process.argv[2];
  if (arg === '--write') {
    const { path, want, ok } = checkReadme();
    if (!ok) writeFileSync(path, want);
    console.log(ok ? 'README.md package table is up to date' : 'README.md package table rewritten');
  } else if (arg === '--check') {
    const { ok } = checkReadme();
    if (!ok) {
      console.error('README.md package table is stale: run node scripts/readme-table.mjs --write');
      process.exit(1);
    }
    console.log('README.md package table is up to date');
  } else {
    console.log(renderTable());
  }
}
